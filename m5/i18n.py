_lang = "es"


def detect_lang():
    for var in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        val = os.environ.get(var)
        if val:
            return "es" if val.lower().startswith("es") else "en"
    return "en"


def set_lang(lang):
    global _lang
    _lang = lang if lang in STRINGS else "en"


def get_lang():
    return _lang


def t(key, *args):
    s = STRINGS[_lang].get(key) or STRINGS["es"].get(key) or key
    return s.format(*args) if args else s


def plural(n):
    return t("pieces_one") if n == 1 else t("pieces_n", n)


def level_name(index, es_name):
    if _lang == "en" and index < len(LEVEL_NAMES_EN):
        return LEVEL_NAMES_EN[index]
    return es_name
